/** 鏡中那隻照的是同伴（座位 0 跟我不同角色）：事件整句換成「假的同伴」版 */
function mirrorEventText(hero: string | undefined, original: string): string | undefined {
  const h = hero ?? 'ninja';
  // 敘事情境住在 `dialogue.ts`（`setCoopStory`），這裡只讀鏡子照的是誰
  const mirror = coopMirror();
  if (!mirror || mirror === h) return undefined;
  return MIRROR_EVENT_TEXT[h]?.[mirror]?.[original];
}

