/** 這一局整局狀態裡用得到的那幾格（兩台同步的那一份） */
export type PairRunView = Pick<RunState, 'act' | 'floor' | 'flags' | 'players'>;

/**
 * 貓窩這一格兩人要不要演一段、演哪一段（`ui/screens/rest.ts` 用 `playOnce` 照字面播）。
 *
 * - 14 樓（關主前一晚）：兩人版獨白，旗標跟單人獨白同一個（`restBeforeBoss<關>`），播了就不會再播單人那段。
 * - 第一、二關其他貓窩：這一關還沒聊過就聊（旗標 `coopChat<關>`）。
 * - 有人倒下：不演（對著躺著的人聊天很怪），也不設旗標——閒聊留到同一關下一個貓窩，14 樓那格畫面退回單人獨白。
 * 回 null＝這一格沒有兩人版。
 */
export function coopRestScene(run: PairRunView): { flag: string; lines: DialogueLine[] } | null {
  const key = coopPairKey(run.players.map((p) => p.hero));
  if (key === null || run.players.some((p) => p.down)) return null;
  const eve = run.floor % 15 === 14;   // 關內樓層 14＝關主前一晚那一格（跟 rest.ts 單人獨白同一條判斷）
  const flag = eve ? `restBeforeBoss${run.act}` : `coopChat${run.act}`;
  if (run.flags[flag]) return null;
  const lines = eve ? COOP_REST_BEFORE_BOSS[key]?.[run.act - 1] : run.act <= 2 ? COOP_REST_CHATS[key]?.[run.act - 1] : undefined;
  return lines && lines.length ? { flag, lines: [...lines] } : null;
}

