/**
 * 這三隻關主的開場／倒下有沒有這一組搭檔的兩人版。`heroes` 是整局的兩位角色（`run.players`，兩台同步的那一份）。
 * `soloDefeat` 是這隻關主的單人倒下段（`dialogue.bossDefeatById[bossId]`，呼叫端手上就有）：老住持那種「關主那幾句照單人版」要用。
 * 回 null＝照舊單人版；回陣列＝**照字面播**。師父那場另走 `dialogue.ts` 的 `coopBossLines`。
 */
export function coopBossPair(bossId: string, stage: 'intro' | 'defeat', heroes: readonly (string | undefined)[],
  soloDefeat: readonly DialogueLine[] = []): DialogueLine[] | null {
  const key = coopPairKey(heroes);
  const set = key === null ? undefined : COOP_BOSS_EXTRA[bossId]?.[key];
  if (!set) return null;
  if (stage === 'intro') return set.intro.map((l) => ({ ...l }));
  if (set.defeat) return set.defeat.map((l) => ({ ...l }));
  if (!set.defeatTail) return null;
  // 關主自己的那幾句照單人版（說話者不是主角的那幾句），主角那句換成兩人接話；單人段不在手上就不演（照舊單人版）
  const his = soloDefeat.filter((l) => l.speaker !== '球球');
  return his.length ? [...his.map((l) => ({ ...l })), ...set.defeatTail.map((l) => ({ ...l }))] : null;
}
