const MASTER: Readonly<Record<string, string>> = {
  'feifei+ninja': '你們師父', 'dangdang+ninja': '你師父', 'fengfeng+ninja': '你師父',
  'dangdang+feifei': '你師父', 'feifei+fengfeng': '你師父', 'dangdang+fengfeng': '大俠貓',
};

interface BossPair {
  intro: DialogueLine[];
  /** 倒下：整段（關主的話也改成對兩個人講） */
  defeat?: DialogueLine[];
  /**
   * 倒下：**關主那幾句照單人版**、後面接這兩句。老住持用這個——他倒下那句另一位編劇會改（塔的來歷），
   * 這裡不抄原文，改了也跟著走。
   */
  defeatTail?: DialogueLine[];
}

type Two = [DialogueLine, DialogueLine];
/** 六組搭檔各自的甲、乙兩句，組成一隻關主的整張表 */
function perPair(lines: Readonly<Record<string, { intro: Two; defeat: Two }>>,
  build: (key: string, intro: Two, defeat: Two) => BossPair): Readonly<Record<string, BossPair>> {
  return Object.fromEntries(Object.entries(lines).map(([k, v]) => [k, build(k, v.intro, v.defeat)]));
}

