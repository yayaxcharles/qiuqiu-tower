const q = (text: string): DialogueLine => ({ speaker: '球球', text });
const f = (text: string): DialogueLine => ({ speaker: '菲菲', text });
const d = (text: string): DialogueLine => ({ speaker: '噹噹', text });
const g = (text: string): DialogueLine => ({ speaker: '封封', text });
const boss = (text: string): DialogueLine => ({ speaker: '塔主', text });

/** 這一局兩位的搭檔鍵：排序過的兩個角色（跟 `dialogue.ts` 的 `pairKey` 同一套）。一個人、或兩位同角色回 null */
export function coopPairKey(heroes: readonly (string | undefined)[]): string | null {
  if (heroes.length !== 2) return null;
  const [a, b] = heroes.map((h) => h ?? 'ninja');
  return a === b ? null : [a!, b!].sort().join('+');
}

