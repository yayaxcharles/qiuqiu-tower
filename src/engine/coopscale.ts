import type { EnemyPool } from './types';

/**
 * 兩個人一起打時魔物要放大多少（2026-09-11）。
 *
 * 抄的是《殺戮尖塔 2》的規則，因為那是同一類遊戲裡唯一有大量實戰資料的答案
 * （查證：sts2front 的雙人指南、STS2 Wiki 的連線篇、Steam 討論串，2026-09-11）：
 *
 * **只放大血量，傷害一點都不動。** 一招打 12 點，一個人打是 12、兩個人打還是 12。
 *
 * 為什麼不是「把傷害也乘 1.5」：那會讓每一招都變成算術題，玩家得重新學一次
 * 每隻怪打多痛；而血量變多只是把仗打長一點，牌與秘寶的判斷完全不用重學。
 * 二代四個人一起玩也是同一套，已經被驗過了。
 *
 * **雙人為什麼反而比較難**（二代玩家的普遍體感）：不在血量，在**範圍攻擊**
 * ——一招打全體等於總輸出翻倍。我們這邊也一樣：規則二是「一招隨機挑一位打」，
 * 所以單體招的傷害其實被攤掉一半，真正會痛的是打全體的那些。
 * 平衡要盯的是這個，不是血量倍率。
 */

/** 幾個人 → 各池的血量倍率。1 人一律 1（單機完全不受影響） */
const COOP_HP: Record<EnemyPool, readonly number[]> = {
  //        1人   2人   3人（先留著，我們今天只做兩人）
  '弱':     [1, 1.5, 2.0],
  '中':     [1, 1.5, 2.0],
  '強':     [1, 1.5, 2.0],
  '大魔物': [1, 1.65, 2.05],   // 菁英放大得多一點：它們本來就是「值得停下來算一輪」的關卡
  '塔主':   [1, 1.75, 2.5],
  '召喚':   [1, 1.5, 2.0],     // 小弟跟著主場一起放大，不然兩個人三兩下清光、召喚失去意義
};

/**
 * 這一場的魔物血量要乘多少。
 *
 * **單機一定回 1**，而且是查表的第一格——不是算出來的，所以不可能因為改係數
 * 而不小心動到單機的平衡（那幾條等號式的錨會立刻抓到）。
 */
export function coopHpMul(pool: EnemyPool, players: number): number {
  const row = COOP_HP[pool];
  return row[Math.min(Math.max(players, 1), row.length) - 1] ?? 1;
}
