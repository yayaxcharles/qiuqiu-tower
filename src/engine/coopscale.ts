import type { EnemyPool } from './types';

/**
 * 兩個人一起打時魔物要放大多少（2026-09-11）。
 *
 * 抄的是《殺戮尖塔 2》的規則，因為那是同一類遊戲裡唯一有大量實戰資料的答案
 * （查證：sts2front 的雙人指南、STS2 Wiki 的連線篇、Steam 討論串，2026-09-11）：
 *
 * **只放大血量，傷害一點都不動。** 一招打 12 點，一個人打是 12、兩個人打還是 12。
 *
 * 為什麼不是「把傷害也乘 1.5」：那會讓每一招都變成算術題，玩家得重新學一次
 * 每隻怪打多痛；而血量變多只是把仗打長一點，牌與秘寶的判斷完全不用重學。
 * 二代四個人一起玩也是同一套，已經被驗過了。
 *
 * **雙人為什麼反而比較難**（二代玩家的普遍體感）：不在血量，在**範圍攻擊**
 * ——一招打全體等於總輸出翻倍。
 *
 * **這一段 2026-09-16 更正**：原本寫「我們這邊規則二是一招隨機挑一位打，
 * 單體招的傷害被攤掉一半」——那是 2026-09-15 之前的事。現在
 * `actions.ts` 的 `ENEMY_HITS_EVERYONE` 是開的，**每一招都對每個站著的人各來一次**，
 * 沒有被攤掉這回事。所以要盯的不是範圍攻擊，就是血量倍率（見下面那段大修）。
 */

/**
 * **2026-09-16 大修：原本的數字根本不是殺戮尖塔 2 的數字。**
 * 這份註解從頭就寫著「抄的是殺戮尖塔 2」，可是表裡填的是 1.5／1.65／1.75。
 * 去查官方 wiki 的連線篇，兩個人的真實倍率是 `魔物血量 × 人數 × 關數係數`：
 * 第一關 ×2.2、第二三關 ×2.4、第三關的王 ×2.6——比我們填的多了三分之一還多。
 * 我們照池分而不是照關數分，所以對應成 一般 2.2、大魔物 2.4、塔主 2.6。
 *
 * 用機器人量過（300 局、難度 1、同一批種子，`tests/coop.report.test.ts`）：
 * 改之前雙人通關 22.7%、單人 2.3%，差快十倍；第一關一般戰每人掉血只有單人的六成。
 * 改之後雙人通關 6.7%、每人掉血 6.3 對單人 6.1、關主戰輸掉 40.2% 對單人 51.7%。
 * 也就是「每個人的消耗跟單人差不多，但兩條命還是比較好活」——雙人該有的好處留著。
 *
 * 也試過「關主每隔幾回合多出手一次」（王只有一隻、出手數 1 對 2）。在舊的血量下
 * 那是唯一有效的旋鈕，可是**血量改對之後就不需要了**：兩個一起上會變成到二關 32.7%、
 * 關主輸掉 65.4%，比單人還難。所以沒有做那個機制，省掉一整套「第二次意圖要顯示給玩家看」。
 */

/** 幾個人 → 各池的血量倍率。1 人一律 1（單機完全不受影響） */
const COOP_HP: Record<EnemyPool, readonly number[]> = {
  //        1人   2人   3人（先留著，我們今天只做兩人）
  '弱':     [1, 2.2, 3.3],
  '中':     [1, 2.2, 3.3],
  '強':     [1, 2.2, 3.3],
  '大魔物': [1, 2.4, 3.6],   // 菁英放大得多一點：它們本來就是「值得停下來算一輪」的關卡
  '塔主':   [1, 2.6, 3.9],
  '召喚':   [1, 2.2, 3.3],   // 小弟跟著主場一起放大，不然兩個人三兩下清光、召喚失去意義
};

/**
 * 這一場的魔物血量要乘多少。
 *
 * **單機一定回 1**，而且是查表的第一格——不是算出來的，所以不可能因為改係數
 * 而不小心動到單機的平衡（那幾條等號式的錨會立刻抓到）。
 */
export function coopHpMul(pool: EnemyPool, players: number): number {
  const row = COOP_HP[pool];
  return row[Math.min(Math.max(players, 1), row.length) - 1] ?? 1;
}
