/**
 * 兩個人一起打時魔物要放大多少（2026-09-11）。
 *
 * 抄的是《殺戮尖塔 2》的規則，因為那是同一類遊戲裡唯一有大量實戰資料的答案
 * （查證：sts2front 的雙人指南、STS2 Wiki 的連線篇、Steam 討論串，2026-09-11）：
 *
 * **只放大血量，傷害一點都不動。** 一招打 12 點，一個人打是 12、兩個人打還是 12。
 *
 * 為什麼不是「把傷害也乘 1.5」：那會讓每一招都變成算術題，玩家得重新學一次
 * 每隻怪打多痛；而血量變多只是把仗打長一點，牌與秘寶的判斷完全不用重學。
 * 二代四個人一起玩也是同一套，已經被驗過了。
 *
 * **雙人為什麼反而比較難**（二代玩家的普遍體感）：不在血量，在**範圍攻擊**
 * ——一招打全體等於總輸出翻倍。
 *
 * **這一段 2026-09-16 更正**：原本寫「我們這邊規則二是一招隨機挑一位打，
 * 單體招的傷害被攤掉一半」——那是 2026-09-15 之前的事。現在
 * `actions.ts` 的 `ENEMY_HITS_EVERYONE` 是開的，**每一招都對每個站著的人各來一次**，
 * 沒有被攤掉這回事。所以要盯的不是範圍攻擊，就是血量倍率（見下面那段大修）。
 */

/**
 * **2026-09-16 大修：原本的數字根本不是殺戮尖塔 2 的數字。**
 * 這份註解從頭就寫著「抄的是殺戮尖塔 2」，可是表裡填的是 1.5／1.65／1.75。
 * 去查官方 wiki 的連線篇，兩個人的真實倍率是 `魔物血量 × 人數 × 關數係數`：
 * 第一關 ×2.2、第二三關 ×2.4、第三關的王 ×2.6——比我們填的多了三分之一還多。
 * 我們照池分而不是照關數分，所以對應成 一般 2.2、大魔物 2.4、塔主 2.6。
 *
 * 用機器人量過（300 局、難度 1、同一批種子，`tests/coop.report.test.ts`）：
 * 改之前雙人通關 22.7%、單人 2.3%，差快十倍；第一關一般戰每人掉血只有單人的六成。
 * 照二代的數字（2.2／2.4／2.6）量出來：雙人通關 6.3%、每人掉血 6.3 對單人 6.1、
 * 關主戰輸掉 41.0% 對單人 51.7%——每個人的消耗追平了，但整局通關率還是單人的 2.7 倍。
 *
 * **使用者要再往上推一檔**（2026-09-16），所以現在是 2.6／2.8／3.0：
 * 雙人通關 3.7%、每人掉血 7.7、關主輸掉 54.4%（單人 51.7%）。也就是**每個人扛的比單人重一點**，
 * 通關率仍略高於單人（3.7% 對 2.3%）——兩條命該留的好處留著。再往上一檔 3.0／3.2／3.4 量到
 * 通關 0.7%、到二關 24%，每一項都比單人難，太過頭了。
 *
 * 這把尺**低估雙人**：機器人不會互相掩護、不喊「我來擋」，收局平均只帶 1.7 張互助牌，
 * 所以真人玩起來會比這張表輕鬆。
 * 也就是「每個人的消耗跟單人差不多，但兩條命還是比較好活」——雙人該有的好處留著。
 *
 * 也試過「關主每隔幾回合多出手一次」（王只有一隻、出手數 1 對 2）。在舊的血量下
 * 那是唯一有效的旋鈕，可是**血量改對之後就不需要了**：兩個一起上會變成到二關 32.7%、
 * 關主輸掉 65.4%，比單人還難。所以沒有做那個機制，省掉一整套「第二次意圖要顯示給玩家看」。
 */

/** 幾個人 → 各池的血量倍率。1 人一律 1（單機完全不受影響） */
const COOP_HP: Record<EnemyPool, readonly number[]> = {
  //        1人   2人   3人（先留著，我們今天只做兩人）
  '弱':     [1, 2.6, 3.9],
  '中':     [1, 2.6, 3.9],
  '強':     [1, 2.6, 3.9],
  '大魔物': [1, 2.8, 4.2],   // 菁英放大得多一點：它們本來就是「值得停下來算一輪」的關卡
  '塔主':   [1, 3.0, 4.5],   // 師父另外照遭遇覆寫成 2.4（見下面的 COOP_HP_BY_ENCOUNTER）；這格只剩第一、二關的關主在用
  '召喚':   [1, 2.6, 3.9],   // 小弟跟著主場一起放大，不然兩個人三兩下清光、召喚失去意義
};

/**
 * 照**遭遇 id** 覆寫上面那張池的表（有列在這裡的遭遇就不看池）。格式跟上面一樣：1 人一律 1。
 *
 * **今天只有師父：兩人 3.0 → 2.4**（2026-09-22 使用者拍板「兩人打師父太難，調低」，其他關主與魔物不動）。
 *
 * 上面塔主那格的 3.0 是 2026-09-16 對著「師父後兩條血沒放大」的舊寫法量的——那時連線時只有第一條血是三倍。
 * 同一天修好換血條（`actions.ts`：後兩條也乘這場的倍率）之後，連線師父的總血量從 900（360＋240＋300）
 * 變成 1980（三條都乘 3.0），多了一倍多，所以重量一次。改成 2.4 是 1584（288＋576＋720）。
 *
 * 量測（難度 1，機器人；雙人 48000 局、單人 48000 局，同一批種子只換師父倍率）。
 * 三組搭檔依序是 球球＋球球／噹噹＋球球／封封＋球球：
 *
 * | 師父倍率 | 雙人通關           | 雙人打師父勝率     | 死在第三關         |
 * |----------|--------------------|--------------------|--------------------|
 * | 3.0（舊）| 1.43／1.01／0.72%  | 42／40／34%        | 80／85／87%        |
 * | 2.6      | 1.59／1.18／0.86%  | 47／47／41%        | 78／83／84%        |
 * | **2.4**  | 1.72／1.28／0.91%  | 51／51／44%        | 76／81／83%        |
 * | 2.2      | 1.87／1.35／1.03%  | 55／54／49%        | 74／80／81%        |
 * | 2.0      | 1.99／1.43／1.05%  | 59／57／50%        | 72／79／80%        |
 *
 * 單人（四隻貓 球球／菲菲／噹噹／封封）：通關 3.31／3.03／2.09／0.90%，打師父 34／45／56／29%，死在第三關 78／82／78／87%。
 *
 * 選 2.4 的理由：
 *  - **雙人的通關率靠這一格補不到單人的中段**（約 2%）。雙人卡在「走到師父面前」——到第三關只有 5～7%
 *   （單人 7～17%），第一關關主勝率 34～39%（單人 44～66%）。就算師父倍率降到 2.0，通關也只有 1.05～1.99%。
 *   再往下調，只會把師父這一場變成白送。
 *  - 所以用「打師父勝率要跟單人同一個範圍」當上限：2.4 是 44～51%，落在單人 29～56% 裡而且沒頂到邊；
 *   2.2 的球球＋球球已經 55%，碰到單人最高的那隻（噹噹 56%）。
 *  - 這把尺**低估雙人**（見上面：機器人不會互相掩護），真人會比表上好打，所以寧可停在 2.4、不壓到 2.2。
 *  - 死在第三關 76～83%，跟單人 78～87% 同一級。
 * 要重量：雙人 `coopRun('coop-<i>', 1, 搭檔)`，i 從 0 到 47999；單人 `smartRun('smart-<i>' 與 'smartB-<i>', 1, 貓)`，i 從 0 到 23999。
 */
export const COOP_HP_BY_ENCOUNTER: Readonly<Record<string, readonly number[]>> = {
  //               1人  2人  3人（照池那張表的比例留著，今天只做兩人）
  tower_master: [1, 2.4, 3.6],
};

/**
 * 這一場的魔物血量要乘多少。`encounterId` 有給、又列在 `COOP_HP_BY_ENCOUNTER` 裡，就用那一列。
 * 開戰（`combat.ts` 的 `startCombat`）與機器人的倍率覆寫（`coopbot.ts` 的 `applyTuning`）都要把遭遇 id 傳進來，
 * 兩邊算出來的倍率才會一樣；師父換血條（`actions.ts`）沿用開戰那一刻算好的 `cs.mods.hpMul`，自動一致。
 *
 * **單機一定回 1**，而且是查表的第一格——不是算出來的，所以不可能因為改係數
 * 而不小心動到單機的平衡（那幾條等號式的錨會立刻抓到）。
 */
export function coopHpMul(pool: EnemyPool, players: number, encounterId?: string): number {
  const own = encounterId !== undefined && Object.prototype.hasOwnProperty.call(COOP_HP_BY_ENCOUNTER, encounterId)
    ? COOP_HP_BY_ENCOUNTER[encounterId] : undefined;
  const row = own ?? COOP_HP[pool];
  return row[Math.min(Math.max(players, 1), row.length) - 1] ?? 1;
}
