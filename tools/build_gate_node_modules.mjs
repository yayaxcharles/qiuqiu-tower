// 推送閘門用：在暫時工作目錄裡建一個只含 package-lock.json 列出的套件的 node_modules
// （2026-09-23 稽核 中-2）。
//
// 為什麼要有這支：舊做法是把本機整個 node_modules 借（junction）過去，本機多裝的
// 套件（`@types/node`、`happy-dom` 那 8 個，鎖檔裡沒有）會被一起借走，於是
// 「測試或工具用到的 node: 函式忘了宣告」「測試偷用 happy-dom」這兩種錯，閘門看不到，
// 要到雲端 `npm ci` 之後才紅（GitHub Actions 的 node_modules 是照鎖檔裝的，沒有那 8 個）。
// 這支把閘門的 node_modules 也照鎖檔裝，兩邊才會一致。
//
// 用法：node tools/build_gate_node_modules.mjs <來源 node_modules 路徑>
// 要在「要推的那一筆提交」的暫時工作目錄裡跑（cwd 是那個工作目錄，讀那裡的
// package-lock.json、在那裡的 node_modules/ 底下建連結）。
//
// 做法：**不重新 npm install**——鎖檔裡的套件，本機這份主 node_modules 早就照鎖檔裝過了，
// 逐一用 junction（Windows 的目錄重分析點，不需要系統管理員權限）連結過去，不必等下載，
// 一次推送多花的時間是毫秒級的。平台限定的 optional 套件（cloudflare workerd 的四個
// 作業系統版本之類）本機只會裝到對應這台機器的那一個，其餘照鎖檔標的 optional 直接跳過，
// 不算錯；鎖檔要求、但本機真的沒裝到的**非** optional 套件才是真的裝壞了，直接判失敗。
import { existsSync, mkdirSync, readFileSync, symlinkSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const srcRoot = process.argv[2];
if (!srcRoot) {
  console.error('[鎖檔 node_modules] 缺來源路徑：node tools/build_gate_node_modules.mjs <來源 node_modules>');
  process.exit(1);
}

const lock = JSON.parse(readFileSync('package-lock.json', 'utf-8'));
const packages = lock.packages ?? {};

const destRoot = resolve('node_modules');
mkdirSync(destRoot, { recursive: true });

let linked = 0;
let skippedOptional = 0;
const missingRequired = [];

for (const [key, meta] of Object.entries(packages)) {
  if (key === '' || !key.startsWith('node_modules/')) continue;   // 根套件自己、或不在 node_modules 底下的項目
  const rel = key.slice('node_modules/'.length);
  const src = join(srcRoot, rel);
  const dest = join(destRoot, rel);
  if (existsSync(dest)) continue;                                 // 已經連過（不會發生，暫時工作目錄一律全新，防呆而已）
  if (!existsSync(src)) {
    if (meta && meta.optional) { skippedOptional++; continue; }    // 這台機器裝不到的平台限定套件，鎖檔本來就標了 optional
    missingRequired.push(rel);
    continue;
  }
  mkdirSync(dirname(dest), { recursive: true });
  symlinkSync(resolve(src), resolve(dest), 'junction');
  linked++;
}

// `.bin` 底下的執行檔捷徑（vitest／tsc／wrangler…）指的都是鎖檔裡的套件，整包借過去最省事，
// 不用逐一解析每支捷徑實際指到哪個套件
const srcBin = join(srcRoot, '.bin');
const destBin = join(destRoot, '.bin');
if (existsSync(srcBin) && !existsSync(destBin)) symlinkSync(resolve(srcBin), resolve(destBin), 'junction');

if (missingRequired.length > 0) {
  console.error(`[鎖檔 node_modules] 主資料夾的 node_modules 缺這幾個鎖檔要求的套件（先在主資料夾跑 npm ci）：\n${missingRequired.join('\n')}`);
  process.exit(1);
}

console.log(`[鎖檔 node_modules] 連結 ${linked} 個套件、跳過 ${skippedOptional} 個這台裝不到的 optional 套件`);
